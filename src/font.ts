export interface TextOpts {
  color?: string;
  outline?: string | null;
  scale?: number;
  align?: 'left' | 'center' | 'right';
  alpha?: number;
}

const cache = new Map<string, HTMLCanvasElement>();

function parse(c: string): [number, number, number] {
  let h = c.slice(1);
  if (h.length === 3) h = h[0]! + h[0]! + h[1]! + h[1]! + h[2]! + h[2]!;
  const n = parseInt(h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

function bake(str: string, color: string, outline: string | null): HTMLCanvasElement {
  const w = str.length * 6 + 2;
  const h = 9;
  const mask = new Uint8Array(w * h);
  for (let i = 0; i < str.length; i++) {
    const g = GLYPHS[str[i]!] ?? GLYPHS['?']!;
    for (let row = 0; row < 7; row++) {
      const bits = g[row]!;
      for (let col = 0; col < 5; col++) if (bits & (1 << (4 - col))) mask[(row + 1) * w + i * 6 + col + 1] = 1;
    }
  }
  const canvas = document.createElement('canvas');
  canvas.width = w;
  canvas.height = h;
  const ctx = canvas.getContext('2d')!;
  const img = ctx.createImageData(w, h);
  const fc = parse(color);
  const oc = outline ? parse(outline) : null;
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      let c: [number, number, number] | null = null;
      if (mask[i]) c = fc;
      else if (oc) {
        outer: for (let dy = -1; dy <= 1; dy++)
          for (let dx = -1; dx <= 1; dx++) {
            const xx = x + dx;
            const yy = y + dy;
            if (xx >= 0 && yy >= 0 && xx < w && yy < h && mask[yy * w + xx]) {
              c = oc;
              break outer;
            }
          }
      }
      if (c) {
        img.data[i * 4] = c[0];
        img.data[i * 4 + 1] = c[1];
        img.data[i * 4 + 2] = c[2];
        img.data[i * 4 + 3] = 255;
      }
    }
  }
  ctx.putImageData(img, 0, 0);
  return canvas;
}

export function textWidth(str: string, scale = 1): number {
  return (str.length * 6 + 2) * scale;
}

export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, opts: TextOpts = {}): void {
  const str = text.toUpperCase();
  const color = opts.color ?? '#ffffff';
  const outline = opts.outline === undefined ? '#000000' : opts.outline;
  const key = `${str}|${color}|${outline}`;
  let c = cache.get(key);
  if (!c) {
    if (cache.size > 900) cache.clear();
    c = bake(str, color, outline);
    cache.set(key, c);
  }
  const s = opts.scale ?? 1;
  const w = c.width * s;
  let dx = x;
  if (opts.align === 'center') dx = x - w / 2;
  else if (opts.align === 'right') dx = x - w;
  const prevAlpha = ctx.globalAlpha;
  if (opts.alpha !== undefined) ctx.globalAlpha = prevAlpha * opts.alpha;
  ctx.drawImage(c, Math.round(dx), Math.round(y), w, c.height * s);
  ctx.globalAlpha = prevAlpha;
}
